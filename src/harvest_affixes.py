"""#907 — overlay our own wiki-harvested enchantments on the vendored records.

Own item harvest (#911), Phase 2. For records in a SWITCHED family (an item slot,
e.g. `Weapon`), each affix the template mappers read from the item's own page
(src/wiki_enchantments.py, defaults from template code) replaces gear-planner's
affix of the same name when that affix has the same bonus type or the same value,
and is added where gear-planner has none. Affixes no mapper produced — weapon
effects like Holy or Vorpal, crafting markers — are untouched.

All or nothing per item: a record whose page carries a call of a MAPPED template
that the mapper could not read (`Unmapped`) keeps gear-planner's affixes entirely,
so an item is never half-replaced. That record is counted, not hidden.

`wiki_item_affixes.json` (committed; regenerated by
`scripts/build_harvest_affix_shard.py`) holds, per record, the mapped affixes and
the names of mapped templates whose calls were unreadable.
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARD_PATH = os.path.join(ROOT, "data", "seed", "compendium", "wiki_item_affixes.json")

#: Item slots whose enchantments now come from the harvest. Widened family by family
#: as each reaches parity (plan #911, Phase 2).
SWITCHED = ("Weapon", "Armor", "Offhand", "Ring", "Necklace", "Trinket", "Bracers", "Goggles",
            "Helm", "Cloak", "Belt", "Gloves", "Boots", "Quiver")


def load(path: str = SHARD_PATH) -> dict:
    with open(path, encoding="utf-8") as fh:
        shard = json.load(fh)
    if not shard.get("records"):
        raise SystemExit("wiki_item_affixes.json carries no records — refusing to overlay nothing")
    return shard


def fmt(name, value, btype=None):
    """gear-planner's value spelling: `+N` for the enhancement and orb bonuses, the
    integer 1 for a presence (`Bool`), else the number as a string."""
    if btype == "Bool":
        return value
    if (name.startswith("Enhancement Bonus (") or name == "Orb Bonus") and value >= 0:
        return f"+{value}"
    return str(value)


def _merge(gp, ours, stats):
    """Match an item's harvested affixes against gear-planner's as ONE set, in three
    passes, so two legitimate affixes of one name (Quality 2 and Exceptional 2) are
    never read as a mistyped pair:
      1. exact (name, type, value)  -> unchanged
      2. same name and type         -> value replaced in place
      3. same name and value        -> type replaced in place
    What is left of ours is appended; what is left of gear-planner's is untouched.
    Order is gear-planner's, so an unchanged item is byte-identical."""
    result = list(gp)
    free = set(range(len(gp)))
    pending = []
    for o in ours:
        i = next((i for i in sorted(free) if (gp[i].get("name"), gp[i].get("type"), gp[i].get("value")) == o), None)
        if i is None:
            pending.append(o)
        else:
            free.discard(i)
            stats["unchanged"] += 1
    for same in (lambda a, o: a.get("type") == o[1], lambda a, o: a.get("value") == o[2]):
        rest = []
        for o in pending:
            i = next((i for i in sorted(free) if gp[i].get("name") == o[0] and same(gp[i], o)), None)
            if i is None:
                rest.append(o)
            else:
                free.discard(i)
                result[i] = {"name": o[0], "type": o[1], "value": o[2]}
                stats["replaced"] += 1
        pending = rest
    stats["added"] += len(pending)
    return result + [{"name": n, "type": t, "value": v} for n, t, v in pending], ours


def apply(raw_items, shard: dict, switched=SWITCHED):
    recs = shard.get("records") or {}
    stats = {"families": list(switched), "records": 0, "kept_whole": 0, "replaced": 0, "added": 0,
             "unchanged": 0, "problems": []}
    out = []
    for it in raw_items:
        if it.get("slot") not in switched:
            out.append(it)
            continue
        h = recs.get(it.get("name"))
        if h is None:
            stats["problems"].append(f"{it.get('name')!r} is a switched-family record the affix harvest never saw")
            out.append(it)
            continue
        stats["records"] += 1
        if h.get("unread"):
            stats["kept_whole"] += 1
            out.append(it)
            continue
        if it.get("slot") != "Weapon" and any(a[0] == "Enhancement Bonus (Weapon)" for a in h.get("affixes") or []):
            # A non-weapon page written with a weapon kind (`{{Enhancement bonus|i|N}}`
            # on a shield, where `si` was meant): the template renders a weapon
            # enhancement, which a shield cannot carry. Not guessed — kept whole.
            stats["kept_whole"] += 1
            stats["weapon_kind_on_non_weapon"] = stats.get("weapon_kind_on_non_weapon", 0) + 1
            out.append(it)
            continue
        affixes, ours = _merge([dict(a) for a in it.get("affixes") or []],
                               [(n, t, fmt(n, v, t)) for n, t, v in h.get("affixes") or []], stats)
        out.append(dict(it, affixes=affixes))
    return out, stats
